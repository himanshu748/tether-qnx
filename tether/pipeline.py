"""The full loop on a real QNX 8.0 VM: observe, tighten, enforce, attack, report."""
from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path

from .qemu import Vm, compile_policy
from .report import Run, render
from .secpol import parse
from .target import ERRORS_DEV, POLICY_DEV, UNUSED_DEV, Target, launch_cmd
from .tighten import denied, extract, grants, narrow

REMOTE_DIR = "/tmp/tether"


@dataclass
class AppSpec:
    binary: str            # local path of the QNX binary to deploy
    type_name: str         # security type to run it as
    workload: str          # local script exercising normal behaviour
    exploit: str           # local script delivering the attack
    args: str = ""
    settle: float = 2.0


def _deploy(t: Target, app: AppSpec) -> dict[str, str]:
    t.run(f"mkdir -p {REMOTE_DIR}")
    remote = {k: f"{REMOTE_DIR}/{Path(getattr(app, k)).name}" for k in ("binary", "workload", "exploit")}
    for k, r in remote.items():
        t.put(getattr(app, k), r)
    t.run(f"chmod +x {' '.join(remote.values())}")
    return remote


def _exercise(t: Target, app: AppSpec, remote: dict[str, str], scripts: list[str]) -> str:
    t.run(f"{launch_cmd(remote['binary'], app.type_name, app.args)} "
          f"> {REMOTE_DIR}/app.out 2>&1 &")
    time.sleep(app.settle)
    for s in scripts:
        t.run(f"sh {remote[s]}", check=False)
    time.sleep(app.settle)
    t.run(f"slay -f {Path(remote['binary']).name}", check=False)
    return t.cat(f"{REMOTE_DIR}/app.out")


def run(vm: Vm, t: Target, app: AppSpec, root_abilities: list[str], out_dir: Path,
        log=print) -> Run:
    out_dir.mkdir(parents=True, exist_ok=True)

    log("observe   building QNX image with secpolgenerate (--secpol=open)")
    vm.build("open")
    vm.boot(t)
    baseline = _exercise(t, app, _deploy(t, app), ["workload"])
    observed, unused = t.cat(POLICY_DEV), t.cat(UNUSED_DEV)
    (out_dir / "observed.secpol").write_text(observed)
    (out_dir / "observe-errors.txt").write_text(t.cat(ERRORS_DEV))
    vm.stop()
    if not parse(observed).rules_for(app.type_name):
        raise RuntimeError(f"secpolgenerate saw nothing for {app.type_name}")

    log(f"tighten   least-privilege rules for {app.type_name}")
    obs, unu = parse(observed), parse(unused) if unused else None
    pol = extract(obs, app.type_name, unu)
    text = f"# least-privilege policy for {app.type_name}, generated by tether\n" + pol.render()
    (out_dir / f"{app.type_name}.secpol").write_text(text)
    system = out_dir / "system.secpol"
    system.write_text("# observed system policy, " + app.type_name + " narrowed by tether\n"
                      + narrow(obs, app.type_name, unu).render())
    compile_policy(str(system), str(out_dir / "secpol.bin"))

    log("enforce   booting QNX with the policy enforced (--secpol=secure)")
    vm.build("secure", str(system))
    vm.boot(t)
    log("attack    rerunning workload, then the exploit")
    sandboxed = _exercise(t, app, _deploy(t, app), ["workload", "exploit"])
    vm.stop()

    denials = [ln for ln in sandboxed.splitlines() if "not permitted" in ln]
    result = Run(app=Path(app.binary).name, type_name=app.type_name, policy=text,
                 grants=grants(pol, app.type_name), withheld=denied(root_abilities, pol, app.type_name),
                 baseline_log=baseline, sandboxed_log=sandboxed, denials=denials,
                 blocked="OK exec" not in sandboxed and bool(denials))
    (out_dir / "run.json").write_text(result.to_json())
    (out_dir / "report.html").write_text(render(result))
    log(f"verdict   {'exploit blocked' if result.blocked else 'exploit NOT blocked'} · {out_dir / 'report.html'}")
    return result
