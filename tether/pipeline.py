"""The full loop on a live QNX target: observe, tighten, enforce, attack, report."""
from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path

from .report import Run, render
from .secpol import parse
from .target import (ERRORS_DEV, POLICY_DEV, UNUSED_DEV, Target, compile_cmd,
                     launch_cmd, observe_cmd, push_cmd, stop_cmd)
from .tighten import denied, extract, grants

REMOTE_DIR = "/tmp/tether"


@dataclass
class AppSpec:
    binary: str            # local path of the QNX binary to deploy
    type_name: str         # security type to run it as
    workload: str          # local script exercising normal behaviour
    exploit: str           # local script delivering the attack
    args: str = ""
    settle: float = 2.0


def _deploy(t: Target, app: AppSpec) -> dict[str, str]:
    t.run(f"mkdir -p {REMOTE_DIR}")
    remote = {k: f"{REMOTE_DIR}/{Path(getattr(app, k)).name}" for k in ("binary", "workload", "exploit")}
    for k, r in remote.items():
        t.put(getattr(app, k), r)
    t.run(f"chmod +x {' '.join(remote.values())}")
    return remote


def _exercise(t: Target, app: AppSpec, remote: dict[str, str], script: str) -> str:
    t.run(f"{launch_cmd(remote['binary'], app.type_name, app.args)} "
          f"> {REMOTE_DIR}/app.out 2>&1 &")
    time.sleep(app.settle)
    t.run(f"sh {script}", check=False)
    time.sleep(app.settle)
    t.run(f"slay -f {Path(remote['binary']).name}", check=False)
    return t.cat(f"{REMOTE_DIR}/app.out")


def run(t: Target, app: AppSpec, root_abilities: list[str], out_dir: Path) -> Run:
    out_dir.mkdir(parents=True, exist_ok=True)
    remote = _deploy(t, app)

    t.run(observe_cmd())
    time.sleep(app.settle)
    baseline = _exercise(t, app, remote, remote["workload"])
    observed = t.cat(POLICY_DEV)
    unused = t.cat(UNUSED_DEV)
    (out_dir / "observed.secpol").write_text(observed)
    t.run(stop_cmd(), check=False)

    pol = extract(parse(observed), app.type_name, parse(unused) if unused else None)
    text = f"# least-privilege policy for {app.type_name}, generated by tether\n" + pol.render()
    (out_dir / f"{app.type_name}.secpol").write_text(text)

    src, binp = f"{REMOTE_DIR}/policy.secpol", f"{REMOTE_DIR}/policy.bin"
    t.put(str(out_dir / f"{app.type_name}.secpol"), src)
    t.run(compile_cmd(src, binp))
    t.run(push_cmd(binp))

    t.run(f"secpolmonitor -f > {REMOTE_DIR}/monitor.log 2>&1 &", check=False)
    sandboxed = _exercise(t, app, remote, remote["exploit"])
    t.run("slay -f secpolmonitor", check=False)
    denials = [ln for ln in t.cat(f"{REMOTE_DIR}/monitor.log").splitlines() if ln.strip()]
    denials += [ln for ln in t.cat(ERRORS_DEV).splitlines() if ln.strip()]

    result = Run(app=Path(app.binary).name, type_name=app.type_name, policy=text,
                 grants=grants(pol, app.type_name), withheld=denied(root_abilities, pol, app.type_name),
                 baseline_log=baseline, sandboxed_log=sandboxed, denials=denials,
                 blocked="OK exec" not in sandboxed)
    (out_dir / "run.json").write_text(result.to_json())
    (out_dir / "report.html").write_text(render(result))
    return result
