"""tether: least-privilege QNX security policies from what an app actually does."""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from pathlib import Path

from .secpol import parse
from .tighten import denied, extract, grants, narrow

ROOT_ABILITIES = [
    "able_create", "able_priv", "channel_connect", "chroot", "clockset", "connection",
    "fork", "interrupt", "io", "mem_phys", "mem_peer", "pathspace", "path_trust",
    "prot_exec", "prot_write_and_exec", "public_channel", "reboot", "setgid", "settypeid",
    "setuid", "signal", "spawn", "spawn_setgid", "spawn_setuid", "trace",
    "xprocess_debug", "xprocess_mem_read", "xprocess_query",
]


def cmd_tighten(a: argparse.Namespace) -> int:
    observed = parse(Path(a.observed).read_text())
    unused = parse(Path(a.unused).read_text()) if a.unused else None
    pol = extract(observed, a.type, unused)
    if not observed.rules_for(a.type):
        print(f"no rules observed for type {a.type}", file=sys.stderr)
        return 1
    text = f"# least-privilege policy for {a.type}, generated by tether\n" + pol.render()
    out = (narrow(observed, a.type, unused).render() if a.system else text)
    Path(a.output).write_text(out) if a.output else sys.stdout.write(out)
    if a.json:
        summary = {
            "type": a.type,
            "policy": text,
            "grants": [asdict(g) for g in grants(pol, a.type)],
            "withheld": denied(ROOT_ABILITIES, pol, a.type),
        }
        Path(a.json).write_text(json.dumps(summary, indent=2))
    return 0


def cmd_run(a: argparse.Namespace) -> int:
    from .pipeline import AppSpec, run
    from .qemu import Vm
    from .target import Target
    app = AppSpec(binary=a.binary, type_name=a.type, workload=a.workload, exploit=a.exploit)
    r = run(Vm(Path(a.image_dir)), Target(port=a.port), app, ROOT_ABILITIES, Path(a.out))
    return 0 if r.blocked else 2


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="tether", description=__doc__)
    sub = p.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("tighten", help="extract a least-privilege policy for one type")
    t.add_argument("observed", help="copy of /dev/secpolgenerate/policy")
    t.add_argument("--type", required=True, help="security type the app ran as")
    t.add_argument("--unused", help="copy of /dev/secpolgenerate/unused")
    t.add_argument("-o", "--output", help="policy file to write (default stdout)")
    t.add_argument("--json", help="also write a JSON summary for the report")
    t.add_argument("--system", action="store_true",
                   help="write the whole system policy with only this type narrowed")
    t.set_defaults(func=cmd_tighten)
    r = sub.add_parser("run", help="observe, tighten, enforce and attack on a QNX 8.0 VM")
    r.add_argument("binary", help="QNX binary built with qcc")
    r.add_argument("--type", required=True, help="security type to run it as")
    r.add_argument("--workload", required=True, help="script exercising normal behaviour")
    r.add_argument("--exploit", required=True, help="script delivering the attack")
    r.add_argument("--image-dir", default="qnx-image", help="mkqnximage working directory")
    r.add_argument("--port", type=int, default=6022, help="host port forwarded to ssh")
    r.add_argument("--out", default="runs/latest", help="where to write policy and report")
    r.set_defaults(func=cmd_run)
    a = p.parse_args(argv)
    return a.func(a)


if __name__ == "__main__":
    raise SystemExit(main())
