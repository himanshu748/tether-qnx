"""tether CLI: turn a secpolgenerate observation into a least-privilege policy."""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from pathlib import Path

from .secpol import parse
from .tighten import denied, extract, grants

ROOT_ABILITIES = [
    "able_create", "able_priv", "channel_connect", "chroot", "clockset", "connection",
    "fork", "interrupt", "io", "mem_phys", "mem_peer", "pathspace", "path_trust",
    "prot_exec", "prot_write_and_exec", "public_channel", "reboot", "setgid", "settypeid",
    "setuid", "signal", "spawn", "spawn_setgid", "spawn_setuid", "trace",
    "xprocess_debug", "xprocess_mem_read", "xprocess_query",
]


def cmd_tighten(a: argparse.Namespace) -> int:
    observed = parse(Path(a.observed).read_text())
    unused = parse(Path(a.unused).read_text()) if a.unused else None
    pol = extract(observed, a.type, unused)
    if not pol.rules:
        print(f"no rules observed for type {a.type}", file=sys.stderr)
        return 1
    text = f"# least-privilege policy for {a.type}, generated by tether\n" + pol.render()
    Path(a.output).write_text(text) if a.output else sys.stdout.write(text)
    if a.json:
        summary = {
            "type": a.type,
            "policy": text,
            "grants": [asdict(g) for g in grants(pol, a.type)],
            "withheld": denied(ROOT_ABILITIES, pol, a.type),
        }
        Path(a.json).write_text(json.dumps(summary, indent=2))
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="tether", description=__doc__)
    sub = p.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("tighten", help="extract a least-privilege policy for one type")
    t.add_argument("observed", help="copy of /dev/secpolgenerate/policy")
    t.add_argument("--type", required=True, help="security type the app ran as")
    t.add_argument("--unused", help="copy of /dev/secpolgenerate/unused")
    t.add_argument("-o", "--output", help="policy file to write (default stdout)")
    t.add_argument("--json", help="also write a JSON summary for the report")
    t.set_defaults(func=cmd_tighten)
    a = p.parse_args(argv)
    return a.func(a)


if __name__ == "__main__":
    raise SystemExit(main())
